import * as THREE from 'three';
import { GLTFLoader } from 'three/examples/jsm/loaders/GLTFLoader.js';
import { applyPose, facingOf, rigOf } from '../src/renderer/pose3d.js';
window.runModel = async (file, pose, rotY = 0) => {
  const gltf = await new GLTFLoader().loadAsync(file);
  const root = gltf.scene;
  const pivot = new THREE.Group(); pivot.add(root);
  const scene = new THREE.Scene(); scene.add(pivot);
  const box = new THREE.Box3().setFromObject(root), size = box.getSize(new THREE.Vector3()), c = box.getCenter(new THREE.Vector3());
  root.position.set(-c.x, -box.min.y, -c.z);
  const k = 1 / size.y; pivot.scale.setScalar(k);
  scene.updateMatrixWorld(true);
  const face = facingOf(root);
  const info = { size: size.toArray(), face: face && face.toArray(), rig: !!rigOf(root), anims: gltf.animations.length };
  if (pose) applyPose(root, { ...pose, forward: face || undefined });
  const baseYaw = face ? Math.atan2(face.x, face.z) : 0;
  pivot.rotation.y = -baseYaw + rotY * Math.PI / 180;
  scene.add(new THREE.HemisphereLight(0x1E8FFF, 0x05060c, 0.8));
  const kl = new THREE.DirectionalLight(0xcfd8ff, 1.0); kl.position.set(-1.7, 2.4, 2.4); scene.add(kl);
  const rl = new THREE.DirectionalLight(0x1E8FFF, 5.5); rl.position.set(1, 2.2, -2.8); scene.add(rl);
  const rl2 = new THREE.DirectionalLight(0x1E8FFF, 3.3); rl2.position.set(-1, 1.8, -2.8); scene.add(rl2);
  const fl = new THREE.DirectionalLight(0x1E8FFF, 0.7); fl.position.set(0, 0.3, 3); scene.add(fl);
  const r = new THREE.WebGLRenderer({ alpha: true, antialias: true, preserveDrawingBuffer: true });
  r.outputColorSpace = THREE.SRGBColorSpace; r.toneMapping = THREE.ACESFilmicToneMapping; r.setSize(400, 600, false);
  const cam = new THREE.PerspectiveCamera(28, 400 / 600, 0.01, 100);
  const dist = 0.5 / Math.tan(14 * Math.PI / 180) * 1.08; cam.position.set(0, 0.5 + Math.sin(0.07) * dist, dist); cam.lookAt(0, 0.5, 0);
  r.setClearColor(0x0b1226, 1);
  r.render(scene, cam);
  return { url: r.domElement.toDataURL('image/png'), info };
};
